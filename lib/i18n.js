export function translateLabel(lang, label) {
  if (!label) return label;
  return dictionaries[lang]?.labels?.[label] || label;
}

// Porciones y tamaños escritos en español ("20-24 porciones", "8 y 6 pulgadas") mostrados en inglés.
export function trFact(lang, text) {
  if (!text || lang !== "en") return text;
  return String(text).replace(/porciones/gi, "servings").replace(/pulgadas/gi, "inches").replace(/ y /g, " and ");
}
